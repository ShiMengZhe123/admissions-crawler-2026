-- WorkMate/招生项目：gaokao_2026_enrollment
-- 可直接在 DataGrip 中打开并逐条执行。

-- 1. 五校汇总
SELECT
    UNIV_NAME,
    COUNT(*) AS RECORD_COUNT,
    SUM(ENROLLMENT_NUM) AS PLANNED_TOTAL,
    COUNT(DISTINCT REGION_NAME) AS PROVINCE_COUNT
FROM gaokao_2026_enrollment
WHERE GAOKAO_DATE = '2026'
GROUP BY UNIV_NAME
UNION ALL
SELECT
    '合计' AS UNIV_NAME,
    COUNT(*) AS RECORD_COUNT,
    SUM(ENROLLMENT_NUM) AS PLANNED_TOTAL,
    COUNT(DISTINCT REGION_NAME) AS PROVINCE_COUNT
FROM gaokao_2026_enrollment
WHERE GAOKAO_DATE = '2026'
ORDER BY CASE WHEN UNIV_NAME = '合计' THEN 1 ELSE 0 END, UNIV_NAME;

-- 2. 各校省份覆盖
SELECT
    UNIV_NAME,
    REGION_NAME,
    COUNT(*) AS RECORD_COUNT,
    SUM(ENROLLMENT_NUM) AS PLANNED_TOTAL
FROM gaokao_2026_enrollment
WHERE GAOKAO_DATE = '2026'
GROUP BY UNIV_NAME, REGION_NAME
ORDER BY UNIV_NAME, REGION_NAME;

-- 3. 招生明细
SELECT
    ENROLLMENT_ID,
    UNIV_ID,
    UNIV_NAME,
    GAOKAO_DATE,
    REGION_NAME,
    BRANCH_NAME,
    ADMISSIONBATCH_NAME,
    SPECIALTY_NAME,
    ENROLLMENT_DESC,
    ENROLLMENT_NUM,
    OPERATE_ID,
    OPERATE_FLAG,
    OPERATE_TIME,
    OPERATE_IP
FROM gaokao_2026_enrollment
WHERE GAOKAO_DATE = '2026'
ORDER BY UNIV_NAME, REGION_NAME, SPECIALTY_NAME;

-- 4. 额外检查：目标表无主键，检查是否存在完全相同的重复行
SELECT
    UNIV_NAME,
    GAOKAO_DATE,
    REGION_NAME,
    BRANCH_NAME,
    ADMISSIONBATCH_NAME,
    SPECIALTY_NAME,
    ENROLLMENT_DESC,
    ENROLLMENT_NUM,
    COUNT(*) AS COPIES
FROM gaokao_2026_enrollment
GROUP BY
    UNIV_NAME,
    GAOKAO_DATE,
    REGION_NAME,
    BRANCH_NAME,
    ADMISSIONBATCH_NAME,
    SPECIALTY_NAME,
    ENROLLMENT_DESC,
    ENROLLMENT_NUM
HAVING COUNT(*) > 1;
